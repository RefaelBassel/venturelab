// נורמליזציה אחידה של קוד כיתה — המקור היחיד לאמת.
// משמש גם בצד הלקוח (storage) וגם בכל ה-API routes.
//
// הבעיה שזה פותר: תלמידים מקלידים את אותו קוד כיתה בצורות שונות —
// "כיתה י1", "כיתה-י'1", "כיתה י׳1", "כיתהי1" — וכל וריאנט נשמר כנמספייס נפרד,
// כך שמורה רואה רק חלק מהצוותים. כאן אנחנו מסירים רווחים, מקפים, גרשים,
// גרשיים ופיסוק — כך שכל הצורות מתמפות לאותה מחרוזת אחת.

export function normalizeClassId(raw: string): string {
  return (raw || '')
    .trim()
    .toLowerCase()
    // הסר: רווחים, / \ גרש(') גרשיים(") גרש עברי(׳) גרשיים עברי(״) ` . , _ -
    .replace(/[\s/\\'"׳״`.,_-]/g, '');
}

export function toDeviceCode(teamId: string): string {
  return teamId.replace(/-/g, '').slice(0, 8).toUpperCase();
}
